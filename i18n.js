let lang = 'en';

/** Langue préférée du fureteur parmi celles offertes, sinon l'anglais. */
export function browserLanguage() {
  for (const tag of navigator.languages ?? [navigator.language]) {
    const code = tag?.slice(0, 2).toLowerCase();
    if (code in LANGUAGES) return code;
  }
  return 'en';
}

export function getLanguage() {
  return lang;
}

export function setLanguage(code) {
  lang = code in LANGUAGES ? code : 'en';
  document.documentElement.lang = lang === 'zh' ? 'zh-Hans' : lang;
  translatePage();
  return lang;
}

/** Texte de la clé dans la langue courante, avec les {valeurs} remplacées. */
export function t(key, values = {}) {
  const text = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (m, name) => (name in values ? values[name] : m));
}

/** Applique la langue courante aux éléments marqués de index.html. */
export function translatePage(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
  for (const el of root.querySelectorAll('[data-i18n-tip]')) el.dataset.tip = t(el.dataset.i18nTip);
}
